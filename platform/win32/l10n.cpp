const wchar_t* language_name(Language language) {
    return language_name_impl(language);
}

const char* language_code(Language language) {
    switch (language) {
        case Language::en: return "en_US";
        case Language::zhCN: return "zh_CN";
        case Language::zhTW: return "zh_TW";
        case Language::de: return "de_DE";
        case Language::es: return "es_ES";
        case Language::fr: return "fr_FR";
        case Language::ja: return "ja_JP";
        case Language::ko: return "ko_KR";
        case Language::ptBR: return "pt_BR";
        case Language::sv: return "sv_SE";
    }
    return "en_US";
}

Language language_from_code(const std::string& code) {
    if (code == "zh_CN") return Language::zhCN;
    if (code == "zh_TW") return Language::zhTW;
    if (code == "ko_KR") return Language::ko;
    if (code == "ja_JP") return Language::ja;
    if (code == "de_DE") return Language::de;
    if (code == "es_ES") return Language::es;
    if (code == "fr_FR") return Language::fr;
    if (code == "sv_SE") return Language::sv;
    if (code == "pt_BR") return Language::ptBR;
    return Language::en;
}

Language system_language() {
    wchar_t name[LOCALE_NAME_MAX_LENGTH]{};
    if (GetUserDefaultLocaleName(name, LOCALE_NAME_MAX_LENGTH) == 0) {
        return Language::en;
    }
    const std::wstring locale(name);
    auto starts = [&locale](const wchar_t* prefix) {
        return locale.rfind(prefix, 0) == 0;
    };
    if (starts(L"zh")) {
        return locale.find(L"TW") != std::wstring::npos ||
                       locale.find(L"HK") != std::wstring::npos ||
                       locale.find(L"Hant") != std::wstring::npos
                   ? Language::zhTW
                   : Language::zhCN;
    }
    if (starts(L"ja")) return Language::ja;
    if (starts(L"ko")) return Language::ko;
    if (starts(L"de")) return Language::de;
    if (starts(L"es")) return Language::es;
    if (starts(L"fr")) return Language::fr;
    if (starts(L"pt")) return Language::ptBR;
    if (starts(L"sv")) return Language::sv;
    return Language::en;
}

