#!/usr/bin/env python3
"""Regenerate the website's icon assets from the icon source.

The site is published on its own (Pages serves `site/` only), so it cannot point
at `assets/icon/` and keeps copies of the artwork instead. The site uses the same
plate-free icon as the executable, so both follow one file. Run this after
changing `assets/icon/app-icon-plateless.svg`:

    python tools/export-site-icons.py --site <path to the site directory>

It writes, under `<site>/assets/`:

    icon.svg          copy of the plate-free icon (SVG favicon)
    mark.svg          same file, used as the header mark
    favicon.ico       16/32/48 frames rasterised from the same icon
    icon-source.txt   sha256 of all of the above, so --check can spot staleness

Check without regenerating (no Pillow, no browser needed):

    python tools/export-site-icons.py --site <path> --check

--check exits 1 when the site assets no longer match the icon source.

Requirements: Python 3.8+; Pillow and Edge or Chrome for the .ico frames.
"""

from __future__ import annotations

import argparse
import hashlib
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

RECORD_NAME = "icon-source.txt"
PLATE_FILL = 'fill="url(#bg)"'
FACE_FILLS = ("#5C8CC9", "#354863", "#486991", "#91BCF5", "#61748C", "#7997BC")


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def check_master(path: Path) -> bytes:
    """Return the plate-free master bytes after checking it really is plate-free.

    The header mark is the master drawing as-is; if a base plate ever creeps back
    into it the mark would silently grow a background, so refuse instead.
    """
    data = path.read_bytes()
    text = data.decode("utf-8")
    if PLATE_FILL in text:
        raise SystemExit(
            f"{path} contains a base plate (<rect {PLATE_FILL} />); the header mark needs the plate-free master"
        )
    ET.fromstring(text)  # must be valid XML
    missing = [fill for fill in FACE_FILLS if fill not in text]
    if missing:
        raise SystemExit(f"{path} is missing faces: {', '.join(missing)}")
    for clip in ("url(#C)", "url(#D)", "url(#E)"):
        if clip not in text:
            raise SystemExit(f"{path} is missing clip {clip}")
    return data


def read_record(path: Path) -> dict[str, str]:
    record: dict[str, str] = {}
    if not path.is_file():
        return record
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        parts = line.split(None, 1)
        if len(parts) == 2:
            record[parts[0]] = parts[1].strip()
    return record


def write_record(path: Path, source_name: str, source: bytes, outputs: dict[str, bytes]) -> None:
    lines = [
        "# Generated by tools/export-site-icons.py -- do not edit by hand.",
        "# Run that script after changing the icon source; --check compares these hashes.",
        f"source {source_name}",
        f"source-sha256 {sha256(source)} {len(source)}",
    ]
    for name, data in outputs.items():
        lines.append(f"{name}-sha256 {sha256(data)} {len(data)}")
    with path.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write("\n".join(lines) + "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description="Regenerate the website icon assets from the icon source.")
    parser.add_argument("--site", default="site", help="site directory that holds assets/ (default: site)")
    parser.add_argument(
        "--source",
        default="assets/icon/app-icon-plateless.svg",
        help="plate-free icon used for the favicon and the header mark",
    )
    parser.add_argument("--check", action="store_true", help="only verify the site assets are up to date")
    args = parser.parse_args()

    source_path = Path(args.source)
    if not source_path.is_file():
        raise SystemExit(f"icon source not found: {source_path}")
    site_assets = Path(args.site) / "assets"
    record_path = site_assets / RECORD_NAME

    source_bytes = check_master(source_path)
    mark_bytes = source_bytes

    if args.check:
        record = read_record(record_path)
        if not record:
            print(f"stale: {record_path} is missing; run tools/export-site-icons.py")
            return 1
        problems: list[str] = []
        expected_source = f"{sha256(source_bytes)} {len(source_bytes)}"
        if record.get("source") != args.source:
            problems.append(f"source path changed: recorded {record.get('source')}, now {args.source}")
        if record.get("source-sha256") != expected_source:
            problems.append("icon source changed since the site assets were generated")
        for name, data in (("icon.svg", source_bytes), ("mark.svg", mark_bytes)):
            path = site_assets / name
            if not path.is_file():
                problems.append(f"{name} is missing")
            elif record.get(f"{name}-sha256") != f"{sha256(path.read_bytes())} {path.stat().st_size}":
                problems.append(f"{name} does not match what the icon source produces")
        favicon = site_assets / "favicon.ico"
        if not favicon.is_file():
            problems.append("favicon.ico is missing")
        elif record.get("favicon.ico-sha256") != f"{sha256(favicon.read_bytes())} {favicon.stat().st_size}":
            problems.append("favicon.ico is stale or was regenerated outside this script")
        if problems:
            for problem in problems:
                print(f"stale: {problem}")
            print("run: python tools/export-site-icons.py --site " + args.site)
            return 1
        print("site icons are up to date")
        return 0

    site_assets.mkdir(parents=True, exist_ok=True)
    (site_assets / "icon.svg").write_bytes(source_bytes)
    (site_assets / "mark.svg").write_bytes(mark_bytes)

    exporter = Path(__file__).with_name("export-icons.py")
    if not exporter.is_file():
        raise SystemExit(f"missing {exporter}; it renders the .ico frames")
    favicon = site_assets / "favicon.ico"
    result = subprocess.run(
        [sys.executable, str(exporter), "--source", str(source_path), "--out", str(favicon), "--sizes", "16,32,48"],
        check=False,
    )
    if result.returncode != 0 or not favicon.is_file():
        raise SystemExit("favicon generation failed")

    write_record(
        record_path,
        args.source,
        source_bytes,
        {
            "icon.svg": source_bytes,
            "mark.svg": mark_bytes,
            "favicon.ico": favicon.read_bytes(),
        },
    )
    print(f"icon.svg    {len(source_bytes)} B  (copy of {args.source})")
    print(f"mark.svg    {len(mark_bytes)} B  (same source)")
    print(f"favicon.ico {favicon.stat().st_size} B")
    print(f"record      {record_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
